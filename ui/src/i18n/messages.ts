type MessageValues = Record<string, string | number | null | undefined>;
type MessageValue = string | ((values?: MessageValues) => string);

export type I18nMessages = Record<string, MessageValue>;

function getString(values: MessageValues | undefined, key: string): string {
  const value = values?.[key];
  return typeof value === "string" ? value : value == null ? "" : String(value);
}

function getNumber(values: MessageValues | undefined, key: string): number {
  const value = values?.[key];
  return typeof value === "number" ? value : Number(value ?? 0);
}

